"""Write the paper's table of the beam search against random restarts at equal CPU time (Table 6,
tables/restarts.tex) from the summary printed by paper/ties_vs_restarts.py: its markdown rows under
"## all0", "## all1" and "## sfxmd0", saved to a file, e.g.

    python3 paper/ties_vs_restarts.py summary tvr > tvr/summary.md
    python3 restarts_table.py tvr/summary.md restarts.tex

usage: python3 restarts_table.py SUMMARY.md OUT.tex

The summary of the paper's server run (Oct 28-29, 2026; printed on Oct 29, one record per seed) is
data/restarts_summary.md of the paper sources. Means are over the seeds; the lower one is in bold.
"""
import os
import sys

PAIRS = [("all0", r"\emph{all}, $s=0$"), ("all1", r"\emph{all}, $s=1$"), ("sfxmd0", r"\emph{sfx} + MD, $s=0$")]
# summary label -> paper label; table order: the 16x16 matrices, then the 32x32 matrices (AES first),
# so that each block matches its "lower / equal / higher" row
ROWS = [
    ("SmallScale AES [CMR05]", "SmallScale AES"),
    ("Joltik [JNP15]", "Joltik"),
    ("SKOP15 Hadamard 16", "[SKOP15] Hadamard"),
    ("LS16 circulant 16", "[LS16] circulant"),
    ("LW16 circulant 16", "[LW16] circulant"),
    ("SS16 Toeplitz 16", "[SS16] Toeplitz"),
    ("JPST17 16", "[JPST17]"),
    ("SKOP15 involutory 16", "[SKOP15] involutory"),
    ("LW16 involutory 16", "[LW16] involutory"),
    ("SS16 involutory 16", "[SS16] involutory"),
    ("JPST17 involutory 16", "[JPST17] involutory"),
    None,
    ("AES MixColumns [DR02]", "AES MixColumns"),
    ("SKOP15 Hadamard 32", "[SKOP15] Hadamard"),
    ("LS16 circulant 32 (SFX23 matrix)", "[LS16] circulant"),
    ("LW16 32", "[LW16]"),
    ("BKL16 circulant 32", "[BKL16] circulant"),
    ("SS16 Toeplitz 32", "[SS16] Toeplitz"),
    ("JPST17 subfield 32", "[JPST17] subfield"),
    ("SKOP15 involutory 32", "[SKOP15] involutory"),
    ("LW16 involutory 32", "[LW16] involutory"),
    ("SS16 involutory 32", "[SS16] involutory"),
    ("KLSW17 32", "[KLSW17]"),
    ("LSL+19 HW168 #130 (SFX23 matrix M)", "[LSL+19] HW168 \\#130"),
]

# permutation-equivalent matrices (Sec. 4 of the paper) form one problem; the tallies count each problem once
PROBLEM = {"Joltik [JNP15]": "Joltik", "SKOP15 involutory 16": "Joltik", "LW16 involutory 16": "Joltik",
           "LS16 circulant 16": "LS16c16", "LW16 circulant 16": "LS16c16"}

HEAD = r"""% Generated by restarts_table.py from SOURCE (summary of paper/ties_vs_restarts.py).
% Means over the seeds of the best XOR2 count of each run; the lower of the two in bold.
\begin{table}[tp]
\centering
\caption{Mean XOR2 count over 4 seeds at the minimum depth $D$: one beam search ($W=2000$) per seed against random restarts, i.e., forward runs with the same tie rule (and no slack), repeated until they used the CPU time of the beam search. Bold: the lower mean. Last rows: the problems for which the beam mean is lower, equal or higher (equivalent matrices count once, Sec.~\ref{sec:equiv}).}
\label{tab:restarts}
\small
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}l r r r r r r r r@{}}
\toprule
& & & \multicolumn{2}{c}{\emph{all}, $s=0$} & \multicolumn{2}{c}{\emph{all}, $s=1$} & \multicolumn{2}{c}{\emph{sfx} + MD, $s=0$} \\
\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(l){8-9}
Matrix & size & $D$ & beam & restarts & beam & restarts & beam & restarts \\
\midrule
"""


def read_summary(path):
    data, pair = {}, None
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line.startswith("## "):
            pair = line[3:].split(":")[0].strip()
        elif line.startswith("|") and pair and not line.startswith("|---") and not line.startswith("| Matrix"):
            c = [x.strip() for x in line.strip("|").split("|")]
            label, size, depth = c[0], c[1], int(c[2])
            bfs_mean = float(c[3].split("/")[1])
            rr_mean = float(c[4].split("/")[1])
            data[(pair, label)] = (size, depth, bfs_mean, rr_mean)
    return data


def cell(x, bold):
    return f"\\textbf{{{x:.2f}}}" if bold else f"{x:.2f}"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data = read_summary(sys.argv[1])
    out = [HEAD.replace("SOURCE", os.path.basename(sys.argv[1]))]
    outcome = {}                                  # (pair, size, problem) -> set of outcomes of its matrices
    used = set()
    for r in ROWS:
        if r is None:
            out.append("\\midrule\n")
            continue
        key, name = r
        size = depth = None
        cells = []
        for p, _ in PAIRS:
            if (p, key) not in data:
                sys.exit(f"the summary has no row for pair {p}, matrix {key!r}: the table needs the full run "
                         f"(23 matrices, pairs all0, all1 and sfxmd0)")
            size, depth, b, q = data[(p, key)]
            used.add((p, key))
            cells += [cell(b, b < q), cell(q, q < b)]
            outcome.setdefault((p, size, PROBLEM.get(key, key)), set()).add(0 if b < q else (1 if b == q else 2))
        n = size.replace("x", "$\\times$")
        out.append(f"{{{name}}} & {n} & {depth} & " + " & ".join(cells) + " \\\\\n")
    missing = set(data) - used
    if missing:
        sys.exit(f"rows of the summary not in the table: {sorted(missing)}")
    tally = {(p, s): [0, 0, 0] for p, _ in PAIRS for s in ("16x16", "32x32")}
    nprob = {}
    for (p, size, prob), o in outcome.items():
        if len(o) > 1:
            sys.exit(f"pair {p}: the matrices of problem {prob} disagree; count them by hand")
        tally[(p, size)][o.pop()] += 1
        nprob.setdefault(size, set()).add(prob)
    out.append("\\midrule\n")
    for s, n in (("16x16", "16$\\times$16"), ("32x32", "32$\\times$32")):
        out.append(f"\\multicolumn{{3}}{{@{{}}l}}{{lower / equal / higher, {n} ({len(nprob[s])})}} & "
                   + " & ".join("\\multicolumn{2}{c}{" + " / ".join(map(str, tally[(p, s)])) + "}" for p, _ in PAIRS)
                   + " \\\\\n")
    out.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("".join(out))
    for p, _ in PAIRS:
        print(p, "16x16", tally[(p, "16x16")], "32x32", tally[(p, "32x32")])


if __name__ == "__main__":
    main()
